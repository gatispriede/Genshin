"""Put a collectible on the real map and build a route that assumes teleporting.

With teleports available, the fastest run is not one long walking loop. It is:
warp, clear everything near that warp on foot, warp again. So this groups every
pin by its nearest teleport, orders the pins inside a group as a short walk from
that teleport, and ranks the groups by how many pins they pay out - so a partial
run is still the best partial run.

Basemap handling lives in tools/mapsource.py.

    python -I tools/build-collectible-map.py --label 141 --slug crimson-agate \\
        --title "Crimson Agate" --feeds "Frostbearing Tree"

Writes reference/data/collect-<slug>.js and updates collect-index.json
"""

import datetime
import io
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mapsource import MapSource, TILE          # noqa: E402

INDEX = os.path.join("reference", "data", "collect-index.json")


def arg(name, default=None):
    a = sys.argv
    return a[a.index("--" + name) + 1] if "--" + name in a else default


def main():
    label = int(arg("label", 141))
    slug = arg("slug", "collectible")
    title = arg("title", "Collectible")
    feeds = arg("feeds", "")

    src = MapSource(map_id=arg("map", "2"), level=int(arg("level", 1)))
    raw = src.labelled(label)
    if not raw:
        raise SystemExit("label %d has no pins" % label)

    floors = src.floors()
    pins = []
    for p in raw:
        x, y = src.px(p["x_pos"], p["y_pos"])
        group = p.get("point_group") or {}
        pins.append({"x": x, "y": y,
                     "layer": floors.get(group.get("floor_id")),
                     "depth": p.get("z_level") or 0})

    win = src.window([(p["x"], p["y"]) for p in pins])
    items = win.keep(pins)
    waypoints = win.keep(src.teleports())
    areas = win.keep(src.areas())

    if len(items) != len(pins):
        print("note: %d pin(s) fell outside the tile window"
              % (len(pins) - len(items)), file=sys.stderr)
    if not waypoints:
        raise SystemExit("no teleports in window - cannot build a route")

    # --- teleport-anchored stops ------------------------------------------
    groups = {}
    for i, it in enumerate(items):
        w = win.nearest(waypoints, it["x"], it["y"])
        groups.setdefault((w["x"], w["y"]),
                          {"x": w["x"], "y": w["y"], "kind": w["kind"],
                           "items": []})["items"].append(i)

    stops = []
    for g in groups.values():
        todo, cur, order, walked = list(g["items"]), (g["x"], g["y"]), [], 0.0
        while todo:
            nxt = min(todo, key=lambda i: math.hypot(items[i]["x"] - cur[0],
                                                     items[i]["y"] - cur[1]))
            walked += math.hypot(items[nxt]["x"] - cur[0],
                                 items[nxt]["y"] - cur[1])
            cur = (items[nxt]["x"], items[nxt]["y"])
            order.append(nxt)
            todo.remove(nxt)
        near = win.nearest(areas, g["x"], g["y"])
        stops.append({"x": g["x"], "y": g["y"], "kind": g["kind"],
                      "place": near["name"] if near else None,
                      "items": order, "walk": int(round(walked)),
                      "offSurface": sum(1 for i in order
                                        if items[i]["layer"] or items[i]["depth"])})

    # Most pins per warp first: a partial run is then still the best one.
    stops.sort(key=lambda s: (-len(s["items"]), s["walk"]))

    data = {
        "generatedAt": datetime.date.today().isoformat(),
        "basemap": src.version, "label": label, "slug": slug,
        "title": title, "feeds": feeds,
        "tileSize": TILE, "size": {"w": win.w, "h": win.h},
        "tiles": win.tiles, "areas": areas, "waypoints": waypoints,
        "items": items, "stops": stops,
    }

    out = os.path.join("reference", "data", "collect-%s.js" % slug)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with io.open(out, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/build-collectible-map.py - do not hand-edit. */\n")
        f.write("window.COLLECT = window.COLLECT || {};\nwindow.COLLECT[%s] = "
                % json.dumps(slug))
        json.dump(data, f, ensure_ascii=False)
        f.write(";\n")

    index = {}
    if os.path.exists(INDEX):
        index = json.load(io.open(INDEX, encoding="utf-8"))
    index[slug] = {"title": title, "feeds": feeds, "count": len(items),
                   "stops": len(stops), "file": "collect-%s.js" % slug}
    with io.open(INDEX, "w", encoding="utf-8") as f:
        json.dump(index, f, ensure_ascii=False, indent=1)

    off = sum(1 for i in items if i["layer"] or i["depth"])
    print("%-16s %3d pins (%d off-surface) · %2d warps · biggest %d · %d tiles"
          % (slug, len(items), off, len(stops), len(stops[0]["items"]),
             len(win.tiles)), file=sys.stderr)


if __name__ == "__main__":
    main()
